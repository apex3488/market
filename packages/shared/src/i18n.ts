export const dictionaries: Record<Locale, Record<TKey, string>> = { ru, en };

export function translate(locale: Locale, key: TKey, vars?: Record<string, string | number>): string {
  let s: string = dictionaries[locale]?.[key] ?? dictionaries.ru[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

export function makeT(locale: Locale) {
  return (key: TKey, vars?: Record<string, string | number>) => translate(locale, key, vars);
}

/** Translate an API error code, falling back to a generic message. */
export function errorText(locale: Locale, code: string | undefined): string {
  const key = `err.${code}` as TKey;
  return key in ru ? translate(locale, key) : translate(locale, "common.error");
}
